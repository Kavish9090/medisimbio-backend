package com.medisimbio.backend.ai.dto;

import io.swagger.v3.oas.annotations.media.Schema;

import java.util.List;

/**
 * AI Pre-Consultation Triage Response Contract.
 * Produced by the AI inference service to classify urgency and recommend medical specialties.
 */
@Schema(description = "AI Triage analysis and doctor specialty recommendation")
public record AiTriageResponseDto(

        @Schema(description = "Calculated clinical urgency triage level", example = "URGENT")
        String triageLevel,

        @Schema(description = "Recommended doctor specialty code", example = "PULM")
        String recommendedSpecialtyCode,

        @Schema(description = "Recommended doctor specialty display name", example = "Pulmonology")
        String recommendedSpecialtyName,

        @Schema(description = "Structured clinical intake summary for the consulting physician",
                example = "Adult male with 4-day cough and mild exertional dyspnea. Vital sign check recommended.")
        String clinicalIntakeSummary,

        @Schema(description = "Potential differential observations generated by AI",
                example = "[\"Acute Bronchitis\", \"Viral Upper Respiratory Infection\", \"Early Pneumonia\"]")
        List<String> differentialObservations,

        @Schema(description = "Emergency warning signs requiring immediate emergency room attention",
                example = "[\"Severe chest pain\", \"Cyanosis\", \"Stridor\"]")
        List<String> redFlagWarnings,

        @Schema(description = "Model confidence score (0.0 to 1.0)", example = "0.91")
        Double confidenceScore
) {
}
